#!/usr/bin/env bash
# Publish and sign the Act 2 demo catalog task bundles.
#
# Act 2 of demo/run-demo.sh references two task bundles in the local registry:
#   - tekton-catalog/demo-catalog-task  (signed with the demo catalog key ->
#     classified trusted-task-role: prod by verify-bundle-signatures)
#   - tekton-catalog/demo-unsigned-task (same task content, NOT signed ->
#     the "attacker spoof" negative case, denied at admission)
#
# Task bundles are content-addressed images built by `tkn bundle push`; the
# resulting digest depends on the local tkn/gzip version, so it is NOT stable
# across machines. This script therefore pushes the bundles fresh and records
# the actual digests in demo/manifests/catalog-bundle-ref, which run-demo.sh
# reads instead of hardcoded pins.
#
# The signing keypair lives in secret demo-signing-key (cosign.key/cosign.pub)
# in namespace kind-registry. It is NOT generated by charts/platform-config
# (that chart only creates release-signing-key in managed-tenant), so this
# script generates it on first use per cluster and configures the
# admission-policy chart (attestor demo-catalog-key) with the matching
# public key. On a fresh cluster the key is NEW — that is fine, because
# signing and verification are both configured from the same key here.
#
# Idempotent: safe to re-run (keys and bundles are reused/overwritten,
# admission-policy is helm-upgraded to the same state).
#
# Usage:
#   demo/push-demo-catalog-bundles.sh
set -eo pipefail

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"

# Discover the Konflux demo cluster kubeconfig (no-op if already targeted).
# shellcheck disable=SC1091
source "${SCRIPT_DIR}/kubeconfig.sh"
REPO_DIR="$( cd "${SCRIPT_DIR}/.." >/dev/null 2>&1 && pwd )"

TENANT_NS="default-tenant"
REGISTRY_NS="kind-registry"
BUNDLE_REF_HOST="registry-service.kind-registry"  # in-cluster registry name
BUNDLE_HOST_PORT=30009
BUNDLE_HOST="localhost:${BUNDLE_HOST_PORT}"       # via kubectl port-forward
CATALOG_REPO="tekton-catalog/demo-catalog-task"
UNSIGNED_REPO="tekton-catalog/demo-unsigned-task"
REF_FILE="${SCRIPT_DIR}/manifests/catalog-bundle-ref"
SIGNING_KEY_SECRET="demo-signing-key"
ADMISSION_RELEASE="admission-policy"

say()  { echo "==> $*"; }
note() { echo "    $*"; }
fail() { echo "Error: $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || fail "'$1' is required on PATH ($2)"; }

# ---------------------------------------------------------------- preflight
say "Verifying cluster connection and prerequisites..."
for tool in kubectl helm tkn cosign python3; do
  need "${tool}" "required to publish and sign the demo catalog bundles"
done
kubectl get namespace "${TENANT_NS}" >/dev/null 2>&1 || fail "Namespace ${TENANT_NS} not found."
kubectl get namespace "${REGISTRY_NS}" >/dev/null 2>&1 || fail "Namespace ${REGISTRY_NS} not found."

# Port-forward the in-cluster registry to localhost (same pattern as
# demo/vault-exchange-demo.sh).
say "Port-forwarding registry-service to localhost:${BUNDLE_HOST_PORT}..."
kubectl port-forward -n "${REGISTRY_NS}" svc/registry-service "${BUNDLE_HOST_PORT}:443" >/dev/null 2>&1 &
PORTFWD_PID=$!
cleanup() {
  kill "${PORTFWD_PID}" 2>/dev/null || true
  [ -n "${WORK_DIR:-}" ] && rm -rf "${WORK_DIR}"
}
trap cleanup EXIT
for i in $(seq 1 15); do
  if curl -sk -m 2 "https://${BUNDLE_HOST}/v2/" >/dev/null 2>&1; then break; fi
  sleep 1
done
curl -sk -m 2 "https://${BUNDLE_HOST}/v2/" >/dev/null 2>&1 || fail "Could not port-forward to registry-service."

# Registry credentials extracted from the cluster's registry client secret
say "Extracting in-cluster registry credentials..."
REGISTRY_AUTH_JSON=$(kubectl get secret internal-registry-client-auth -n "${REGISTRY_NS}" \
  -o jsonpath='{.data.\.dockerconfigjson}' | base64 -d)
REGISTRY_USER=$(echo "${REGISTRY_AUTH_JSON}" | python3 -c "import sys,json,base64; d=json.load(sys.stdin)['auths']['${BUNDLE_REF_HOST}']['auth']; print(base64.b64decode(d).decode().split(':',1)[0])")
REGISTRY_PASS=$(echo "${REGISTRY_AUTH_JSON}" | python3 -c "import sys,json,base64; d=json.load(sys.stdin)['auths']['${BUNDLE_REF_HOST}']['auth']; print(base64.b64decode(d).decode().split(':',1)[1])")
[ -n "${REGISTRY_USER}" ] || fail "Could not extract registry credentials."

WORK_DIR=$(mktemp -d /tmp/demo-catalog-bundles.XXXXXX)

# ---------------------------------------------------------------- signing key
say "Ensuring demo catalog signing keypair (secret ${SIGNING_KEY_SECRET} in ${REGISTRY_NS})..."
if kubectl get secret "${SIGNING_KEY_SECRET}" -n "${REGISTRY_NS}" >/dev/null 2>&1 \
   && kubectl get secret "${SIGNING_KEY_SECRET}" -n "${REGISTRY_NS}" \
        -o jsonpath='{.data.cosign\.key}' | base64 -d | grep -q "PRIVATE KEY" \
   && kubectl get secret "${SIGNING_KEY_SECRET}" -n "${REGISTRY_NS}" \
        -o jsonpath='{.data.cosign\.pub}' | base64 -d | grep -q "PUBLIC KEY"; then
  note "Secret ${SIGNING_KEY_SECRET} already exists; reusing the existing keypair."
else
  note "Generating a new cosign keypair (fresh cluster)..."
  COSIGN_PASSWORD="" cosign generate-key-pair --output-key-prefix "${WORK_DIR}/cosign" >/dev/null
  kubectl create secret generic "${SIGNING_KEY_SECRET}" -n "${REGISTRY_NS}" \
    --from-file=cosign.key="${WORK_DIR}/cosign.key" \
    --from-file=cosign.pub="${WORK_DIR}/cosign.pub" \
    --dry-run=client -o yaml | kubectl apply -f - >/dev/null
  note "Created secret ${SIGNING_KEY_SECRET} in ${REGISTRY_NS}."
fi
COSIGN_KEY_FILE="${WORK_DIR}/cosign.key"
kubectl get secret "${SIGNING_KEY_SECRET}" -n "${REGISTRY_NS}" \
  -o jsonpath='{.data.cosign\.key}' | base64 -d > "${COSIGN_KEY_FILE}"
chmod 600 "${COSIGN_KEY_FILE}"
COSIGN_PUB_FILE="${WORK_DIR}/cosign.pub"
kubectl get secret "${SIGNING_KEY_SECRET}" -n "${REGISTRY_NS}" \
  -o jsonpath='{.data.cosign\.pub}' | base64 -d > "${COSIGN_PUB_FILE}"

# ---------------------------------------------------------------- push bundles
# NOTE: bundle digests are NOT stable across tkn versions (the image layer is
# a gzip of the task YAML), so we record the actual digest per push in the
# ref file that run-demo.sh reads.
push_bundle() {  # $1 = repo, $2 = task yaml, $3 = description; echoes digest on stdout
  say "Publishing ${3} bundle ${BUNDLE_REF_HOST}/$1 (idempotent)..." >&2
  local out digest
  out=$(tkn bundle push \
    --remote-skip-tls \
    --remote-username "${REGISTRY_USER}" \
    --remote-password "${REGISTRY_PASS}" \
    "${BUNDLE_HOST}/$1:latest" \
    -f "$2" 2>&1) || { echo "${out}" >&2; fail "tkn bundle push failed for $1"; }
  digest=$(echo "${out}" | grep -o 'sha256:[a-f0-9]*' | head -1)
  [ -n "${digest}" ] || { echo "${out}" >&2; fail "Could not resolve pushed bundle digest for $1."; }
  note "Pushed: ${BUNDLE_REF_HOST}/$1@${digest}" >&2
  echo "${digest}"
}

CATALOG_DIGEST=$(push_bundle "${CATALOG_REPO}" "${SCRIPT_DIR}/manifests/demo-catalog-task.yaml" "signed catalog task")
UNSIGNED_DIGEST=$(push_bundle "${UNSIGNED_REPO}" "${SCRIPT_DIR}/manifests/demo-unsigned-task.yaml" "UNSIGNED attacker-spoof task")

say "Recording bundle refs in ${REF_FILE}..."
cat > "${REF_FILE}" << EOF
# Demo catalog task bundle refs (Act 2), written by demo/push-demo-catalog-bundles.sh.
# Digests are content-addressed but NOT stable across tkn versions, so they
# are recorded here per cluster instead of being hardcoded in run-demo.sh.
CATALOG_TASK_BUNDLE=${BUNDLE_REF_HOST}/${CATALOG_REPO}@${CATALOG_DIGEST}
UNSIGNED_TASK_BUNDLE=${BUNDLE_REF_HOST}/${UNSIGNED_REPO}@${UNSIGNED_DIGEST}
EOF
note "CATALOG_TASK_BUNDLE=${BUNDLE_REF_HOST}/${CATALOG_REPO}@${CATALOG_DIGEST}"
note "UNSIGNED_TASK_BUNDLE=${BUNDLE_REF_HOST}/${UNSIGNED_REPO}@${UNSIGNED_DIGEST}"

# ---------------------------------------------------------------- sign
sign_bundle() {  # $1 = full bundle ref (host/repo@digest)
  # --use-signing-config=false + --tlog-upload=false: key-based signing must
  #   stay off the public Rekor (the ImageValidatingPolicy verifies with insecureIgnoreTlog;
  #   uploading localhost refs to rekor.sigstore.dev is noise). Also prevents
  #   the interactive "private repository" prompt cosign v3 raises in a TTY.
  # --yes: never prompt; setup must run unattended.
  DOCKER_CONFIG="${WORK_DIR}/docker-config" COSIGN_PASSWORD="" cosign sign \
    --key "${COSIGN_KEY_FILE}" \
    --use-signing-config=false \
    --tlog-upload=false \
    --yes \
    --allow-insecure-registry \
    "$1" >/dev/null
}

# cosign reads registry credentials from the docker config; point it at a
# throwaway one so the user's ~/.docker/config.json is never touched.
mkdir -p "${WORK_DIR}/docker-config"
python3 - "$REGISTRY_USER" "$REGISTRY_PASS" "${BUNDLE_HOST}" "${WORK_DIR}/docker-config/config.json" << 'PYEOF'
import base64, json, sys
user, pw, host, out = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
json.dump({"auths": {host: {"auth": base64.b64encode(f"{user}:{pw}".encode()).decode()}}},
          open(out, "w"))
PYEOF

# Key-based signing skips the Rekor transparency log by default (cosign v3),
# which matches the ImageValidatingPolicy's insecureIgnoreTlog (no Rekor in the demo cluster).
say "Signing the catalog bundles with the demo catalog key..."
sign_bundle "${BUNDLE_HOST}/${CATALOG_REPO}@${CATALOG_DIGEST}"
note "Catalog task bundle signed."

# --- Act 3 task bundles -----------------------------------------------------
# trivy-sbom-scan: the scanner task for the secretless CVE-DB access test.
TRIVY_REPO="tekton-catalog/trivy-sbom-scan"
# Demo variant of the scanner task: fetches the JWT-SVID for the CVE
# database audience (stands in for the full Trivy scan task).
TRIVY_DIGEST=$(push_bundle "${TRIVY_REPO}" "${REPO_DIR}/managed-context/tasks/trivy-sbom-scan/0.1-demo/trivy-sbom-scan.yaml" "scanner task")
sign_bundle "${BUNDLE_HOST}/${TRIVY_REPO}@${TRIVY_DIGEST}"
TRIVY_TASK_BUNDLE=${BUNDLE_REF_HOST}/${TRIVY_REPO}@${TRIVY_DIGEST}

# buildah-oci-ta: the builder task for the Zot push-gating test. Demo
# variant: fetches the builder JWT-SVID for the gated registry (stands in
# for the full buildah build task; the act only needs the identity and the
# registry handshake).
BUILDAH_REPO="tekton-catalog/buildah-oci-ta"
BUILDAH_TASK_YAML="${REPO_DIR}/managed-context/tasks/buildah-oci-ta/0.1/buildah-oci-ta.yaml"
[ -f "${BUILDAH_TASK_YAML}" ] || fail "missing ${BUILDAH_TASK_YAML}"
BUILDAH_DIGEST=$(push_bundle "${BUILDAH_REPO}" "${BUILDAH_TASK_YAML}" "builder task")
sign_bundle "${BUNDLE_HOST}/${BUILDAH_REPO}@${BUILDAH_DIGEST}"
BUILDAH_TASK_BUNDLE=${BUNDLE_REF_HOST}/${BUILDAH_REPO}@${BUILDAH_DIGEST}

# Record the Act 3 refs alongside the Act 2 ones.
REF_APPEND=$(cat << REFEOF
TRIVY_TASK_BUNDLE=${TRIVY_TASK_BUNDLE}
BUILDAH_TASK_BUNDLE=${BUILDAH_TASK_BUNDLE}
REFEOF
)
printf '%s\n' "${REF_APPEND}" >> "${REF_FILE}"
rm -rf "${WORK_DIR}/docker-config"

# ---------------------------------------------------------------- admission policy
say "Configuring admission-policy chart with the trusted catalog pattern and key..."
# values-demo.yaml pins the pattern and attestor name; the per-cluster public
# key is injected with --set-file (the keypair is regenerated on fresh
# clusters, so it cannot be committed).
helm upgrade --install "${ADMISSION_RELEASE}" "${REPO_DIR}/charts/admission-policy" \
  -n default --create-namespace \
  -f "${REPO_DIR}/charts/admission-policy/values-demo.yaml" \
  --set-file 'trustedBundles[0].signingKeys[0].publicKey'="${COSIGN_PUB_FILE}" >/dev/null
note "verify-bundle-signatures now verifies tekton-catalog/* against attestor demo-catalog-key."

# ---------------------------------------------------------------- verify
# Admission-webhook verification can exceed the timeout on a cold cache
# (Kyverno re-fetches registry manifests after a restart); retry the creates.
kubectl_create_retry() {
  local attempt payload
  payload=$(cat)  # buffer stdin: retries cannot re-read a pipe
  for attempt in 1 2 3; do
    if printf '%s' "${payload}" | kubectl create -f - "$@"; then return 0; fi
    echo "    [retry ${attempt}/3] admission webhook slow; waiting 20s..."
    sleep 20
  done
  return 1
}

# Force-delete a TaskRun that is stuck Terminating on a chains/results
# finalizer (common right after a cluster restart); otherwise a re-run of
# this script aborts on 'AlreadyExists: object is being deleted'.
delete_taskrun_force() {  # $1 = name, $2 = namespace
  kubectl delete taskrun "$1" -n "$2" --wait=false --ignore-not-found=true >/dev/null 2>&1 || true
  if kubectl get taskrun "$1" -n "$2" >/dev/null 2>&1; then
    kubectl patch taskrun "$1" -n "$2" --type=merge -p '{"metadata":{"finalizers":[]}}' >/dev/null 2>&1 || true
    kubectl delete taskrun "$1" -n "$2" --wait=false --ignore-not-found=true >/dev/null 2>&1 || true
  fi
}

say "Verifying classification on the live cluster..."

# (a) the ImageValidatingPolicy carries the demo-catalog-key attestor
if kubectl get imagevalidatingpolicy verify-bundle-signatures >/dev/null 2>&1; then
  kubectl get imagevalidatingpolicy verify-bundle-signatures \
    -o jsonpath='{.spec.attestors[*].name}' | grep -q demo-catalog-key \
    || fail "ImageValidatingPolicy verify-bundle-signatures does not carry attestor demo-catalog-key."
  note "ImageValidatingPolicy attestor demo-catalog-key present."
fi

# (b) the signed catalog bundle classifies trusted-task-role: prod
delete_taskrun_force demo-catalog-verify "${TENANT_NS}"
cat << EOF | kubectl_create_retry >/dev/null
apiVersion: tekton.dev/v1
kind: TaskRun
metadata:
  name: demo-catalog-verify
  namespace: ${TENANT_NS}
  labels:
    appstudio.openshift.io/application: demo-app
    appstudio.openshift.io/component: demo-app
    app.kubernetes.io/part-of: kubecon-demo
spec:
  taskRef:
    resolver: bundles
    params:
    - name: bundle
      value: ${BUNDLE_REF_HOST}/${CATALOG_REPO}@${CATALOG_DIGEST}
    - name: name
      value: demo-catalog-task
    - name: kind
      value: task
EOF
kubectl wait --for=condition=Succeeded taskrun/demo-catalog-verify -n "${TENANT_NS}" --timeout=120s >/dev/null
ROLE=$(kubectl get taskrun demo-catalog-verify -n "${TENANT_NS}" -o jsonpath='{.metadata.labels.trusted-task-role}')
[ "${ROLE}" = "prod" ] || fail "Signed catalog task classified '${ROLE}', expected 'prod'."
note "Signed catalog task ran and classified trusted-task-role=${ROLE}."
delete_taskrun_force demo-catalog-verify "${TENANT_NS}"

# (c) the unsigned bundle is denied at admission
delete_taskrun_force demo-unsigned-verify "${TENANT_NS}"
if cat << EOF | kubectl apply -f - >/dev/null 2>&1
apiVersion: tekton.dev/v1
kind: TaskRun
metadata:
  name: demo-unsigned-verify
  namespace: ${TENANT_NS}
  labels:
    appstudio.openshift.io/application: demo-app
    appstudio.openshift.io/component: demo-app
    app.kubernetes.io/part-of: kubecon-demo
spec:
  taskRef:
    resolver: bundles
    params:
    - name: bundle
      value: ${BUNDLE_REF_HOST}/${UNSIGNED_REPO}@${UNSIGNED_DIGEST}
    - name: name
      value: demo-catalog-task
    - name: kind
      value: task
EOF
then
  delete_taskrun_force demo-unsigned-verify "${TENANT_NS}"
  fail "Unsigned catalog bundle was admitted; expected admission denial."
fi
note "Unsigned catalog bundle denied at admission, as expected."

say "Done. Act 2 catalog bundles are published, signed, and verified."
